#!/usr/bin/env python3
"""Проверяет отключение диагностики и показывает изменения исполняемой политики."""

from __future__ import annotations

import argparse
from collections import Counter
import functools
import json
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import script_paths  # noqa: E402,F401
import ci_common  # noqa: E402
from ci_common import BASE_BRANCH, HARNESS_BLOCK, KIT_ROLES, ROOT, app_prefix, forge, get_records, msg, payload, run_strict, tracked  # noqa: E402
from generated_sources import generated  # noqa: E402
import tool_pins  # noqa: E402

SOURCE_SUFFIXES = {".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs", ".astro"}
RULE = re.compile(r'''["']([@\w/-]+)["']\s*:\s*(?:\[\s*)?["']?(off|warn|error|0|1|2)["']?(?=[\s,\]])''')
AUTHORED = "HarnessAuthoredCompileFiles"


def source_groups(sources: list[str]) -> dict[str, list[str]]:
    roots = sorted((app_prefix(str(app["path"])) for app in get_records("apps", [], file="project/manifest.json")
                    if app.get("stack") == "node"), key=len, reverse=True)
    groups: dict[str, list[str]] = {}
    for path in sources:
        root = next((prefix for prefix in roots if path.startswith(prefix)), "")
        groups.setdefault(root.rstrip("/") or ".", []).append(path)
    return groups


def first_install(base: str) -> bool:
    return not show(base, ci_common.LOCK).strip()


def project_part(entry: dict, text: str, installing: bool) -> str:
    if not installing or entry.get("role") != "block":
        return text
    return HARNESS_BLOCK.sub(lambda found: "" if found.group(1) == entry.get("block", "core") else found.group(0), text)


@functools.cache
def app_configs() -> frozenset[str]:
    return frozenset(path for app in get_records("apps", [], file="project/manifest.json")
                     for path in (app.get("configs") if isinstance(app.get("configs"), list) else []) if isinstance(path, str))


def policy_file(path: str) -> bool:
    name = Path(path).name
    return path in app_configs() or name in {".editorconfig", "tsconfig.base.json"} or name.endswith(".globalconfig") or (
        name.startswith(("eslint", "tsconfig")) and name.endswith((".js", ".mjs", ".json"))) or (
        path.startswith((".config/", ".harness/scripts/", ".github/workflows/", ".githooks/", ".harness/"))) or (
        path.endswith((".props", ".targets", ".csproj", ".ruleset", ".runsettings")))


def show(base: str, path: str) -> str:
    return (ci_common.base_read(base, path) or b"").decode("utf-8", "replace")


def severities(text: str) -> dict[tuple[str, str], str]:
    section = ""
    result = {}
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("["):
            section = line
        elif ".severity" in line and "=" in line:
            name, value = map(str.strip, line.split("=", 1))
            result[(section, name)] = value
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default=BASE_BRANCH)
    args = parser.parse_args()
    run_strict("git", "rev-parse", "--verify", args.base, unread=msg("gate_tree_unread"))
    failures: list[tuple[str, int, str]] = []
    paths = tracked()
    untracked = [path for path in run_strict("git", "ls-files", "--others", "--exclude-standard", "-z", unread=msg("gate_tree_unread")).split("\0") if path and not payload(path)]
    paths.extend(untracked)
    diffed = {*ci_common.with_kit(run_strict("git", "diff", "--name-only", args.base, unread=msg("gate_tree_unread")).splitlines(),
                                  args.base), *untracked}
    sources = []
    files = ci_common.lock_files()
    installing = first_install(args.base)
    node = "node" in tool_pins.stacks()
    for path in sorted(set(paths)):
        file = Path(ROOT, path)
        if not file.is_file() or generated(path):
            continue
        if file.name == ".editorconfig" or file.name.endswith(".globalconfig"):
            if re.search(rf"^\s*build_property\.{AUTHORED}\s*=", file.read_text(encoding="utf-8"), re.MULTILINE | re.IGNORECASE):
                failures.append((path, 1, msg("integrity_compile_inputs")))
        if file.suffix == ".cs":
            text = file.read_text(encoding="utf-8")
            if re.search(r"^\s*//\s*<auto-generated", text, re.MULTILINE) or file.name.endswith((".g.cs", ".g.i.cs", ".generated.cs", ".Designer.cs")):
                failures.append((path, 1, msg("integrity_generated")))
        if file.suffix in SOURCE_SUFFIXES and node:
            sources.append(path)
        if file.suffix in {".csproj", ".props", ".targets"}:
            xml = ET.parse(file)
            for target in xml.iter():
                if target.tag.rsplit("}", 1)[-1] == "Target" and any(
                    element.tag.rsplit("}", 1)[-1] == "Compile" or element.get("ItemName") == "Compile" for element in target.iter()
                ):
                    failures.append((path, 1, msg("integrity_late_compile")))
            owned = path in app_configs()
            for element in xml.iter():
                name = element.tag.rsplit("}", 1)[-1]
                value = (element.text or "").strip()
                if name == AUTHORED and not owned:
                    failures.append((path, 1, msg("integrity_compile_inputs")))
                if name == "NoWarn":
                    if not owned:
                        failures.append((path, 1, msg("integrity_nowarn")))
                elif name in {"RunAnalyzers", "RunAnalyzersDuringBuild", "RunAnalyzersDuringLiveAnalysis", "EnableNETAnalyzers", "TreatWarningsAsErrors", "EnforceCodeStyleInBuild", "GenerateDocumentationFile", "EnableDefaultCompileItems"} and value.lower() == "false":
                    failures.append((path, 1, msg("integrity_disabled", name)))
                elif name == "CodeAnalysisRuleSet" and value:
                    failures.append((path, 1, msg("integrity_disabled", name)))
                elif name == "SkipCompilerExecution" and value.lower() == "true":
                    failures.append((path, 1, msg("integrity_disabled", name)))
                elif name == "WarningsNotAsErrors" and value.replace("$(WarningsNotAsErrors)", "").strip("; "):
                    failures.append((path, 1, msg("integrity_disabled", name)))

    groups = {os.path.join(ROOT, app): group for app, group in source_groups(sources).items()}
    try:
        parsed = json.loads(subprocess.run(["node", ".harness/scripts/check/diagnostic-comments.mjs"], cwd=ROOT,
                                           input=json.dumps(groups), text=True, encoding="utf-8", capture_output=True,
                                           check=True).stdout) if groups else {"findings": [], "unresolved": []}
        failures += [(finding["path"], finding["line"], msg("integrity_source_directive")) for finding in parsed["findings"]]
        failures += [(os.path.relpath(app, ROOT), 1, msg("integrity_parser", os.path.relpath(app, ROOT)))
                     for app in parsed["unresolved"]]
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        failures.append((".", 1, msg("integrity_parser", ".")))
        if isinstance(error, subprocess.CalledProcessError):
            print(error.stderr, file=sys.stderr)

    changed = sorted(path for path in diffed
                     if not payload(path) and not (Path(ROOT, path).is_file() and generated(path)))
    for path in changed:
        file = Path(ROOT, path)
        if not file.is_file() or not policy_file(path):
            continue
        entry = files.get(path, {})
        if installing and entry.get("role") in KIT_ROLES:
            continue
        current = project_part(entry, file.read_bytes().decode("utf-8", "replace").replace("\r\n", "\n").replace("\r", "\n"),
                               installing)
        if not current:
            continue
        previous = project_part(entry, show(args.base, path), installing)
        if file.name == ".editorconfig" or file.name.endswith(".globalconfig"):
            old = severities(previous)
            if current.count("generated_code = true") > previous.count("generated_code = true"):
                failures.append((path, 1, msg("integrity_generated")))
            levels = {"none": 0, "silent": 1, "suggestion": 2, "warning": 3, "error": 4}
            for key, severity in severities(current).items():
                if (severity in {"none", "silent"} and old.get(key) != severity) or (
                    key in old and levels.get(severity, 4) < levels.get(old[key], 4)
                ):
                    failures.append((path, 1, msg("integrity_severity", ":".join(key))))
        if file.name.startswith("eslint") and file.suffix in {".js", ".mjs"}:
            old_off = Counter(rule for rule, severity in RULE.findall(previous) if severity in {"off", "0"})
            new_off = Counter(rule for rule, severity in RULE.findall(current) if severity in {"off", "0"})
            for rule in (new_off - old_off).elements():
                failures.append((path, 1, msg("integrity_severity", rule)))
            old_rules = Counter((rule, "warn" if level == "1" else "error" if level == "2" else level) for rule, level in RULE.findall(previous))
            new_rules = Counter((rule, "warn" if level == "1" else "error" if level == "2" else level) for rule, level in RULE.findall(current))
            for rule, level in new_rules - old_rules:
                if level == "warn" and old_rules[(rule, "error")] > new_rules[(rule, "error")]:
                    failures.append((path, 1, msg("integrity_severity", rule)))

    policy = [path for path in changed if policy_file(path)]
    report = [msg("integrity_policy_header"), *(f"- `{path}`" for path in policy)] if policy else []
    if report:
        print("\n".join(report))
        forge.step_summary("\n".join(report) + "\n")
    for path, line, reason in failures:
        print(f"{path}:{line}: {reason}")
    print(msg("integrity_failed", len(failures)) if failures else msg("integrity_clean", len(paths)))
    return bool(failures)


if __name__ == "__main__":
    raise SystemExit(main())
